"use client";

import { useEffect, useRef, useState, type FormEvent } from "react";
import type { AnswerBlock, AssistantMessage } from "@/domain/types";
import { useExplorer } from "@/context/ExplorerContext";
import { SUGGESTED_QUESTIONS } from "@/lib/assistant/mockAssistant";
import { excerpt } from "@/lib/repo/refs";
import { EvidenceBadge, formatRef } from "@/components/ui/primitives";

export function AssistantPanel() {
  const { messages, thinking, ask, clearMessages, setAssistantOpen, selectedFile } = useExplorer();
  const [input, setInput] = useState("");
  const endRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    endRef.current?.scrollIntoView({ block: "end" });
  }, [messages, thinking]);

  const submit = (e: FormEvent) => {
    e.preventDefault();
    ask(input);
    setInput("");
  };

  return (
    <aside className="assistant" aria-label="AI assistant">
      <div className="d-flex align-items-center justify-content-between px-3 py-2 border-bottom">
        <div>
          <strong>Assistant</strong>{" "}
          <span className="chip ms-1" title="Answers come from the mock provider, built on the analyzed repository. Gemini arrives in Stage 3.">
            Mock AI
          </span>
        </div>
        <div className="d-flex gap-1">
          {messages.length > 0 && (
            <button type="button" className="btn btn-sm btn-light" onClick={clearMessages}>
              Clear
            </button>
          )}
          <button type="button" className="btn btn-sm btn-light" aria-label="Close assistant" onClick={() => setAssistantOpen(false)}>
            <i className="bi bi-x-lg" aria-hidden="true" />
          </button>
        </div>
      </div>

      <div className="assistant-scroll" aria-live="polite">
        {messages.length === 0 && (
          <div>
            <p className="text-muted">
              Ask about this repository. Answers cite real files and lines, and label what is fact, inference, recommendation or uncertain.
            </p>
            <p className="small text-muted mb-1">
              Current file: <span className="mono">{selectedFile}</span>
            </p>
            <div className="d-flex flex-column gap-2 mt-3">
              {SUGGESTED_QUESTIONS.map((q) => (
                <button key={q} type="button" className="btn btn-sm btn-outline-secondary text-start" onClick={() => ask(q)}>
                  {q}
                </button>
              ))}
              <button type="button" className="btn btn-sm btn-outline-secondary text-start" onClick={() => ask("Explain this file")}>
                Explain this file
              </button>
            </div>
          </div>
        )}
        {messages.map((m) => (
          <MessageView key={m.id} message={m} />
        ))}
        {thinking && <div className="text-muted small">Analyzing repository context…</div>}
        <div ref={endRef} />
      </div>

      <form className="assistant-form" onSubmit={submit}>
        <label htmlFor="assistant-input" className="visually-hidden">
          Ask a question about the repository
        </label>
        <div className="input-group">
          <input
            id="assistant-input"
            className="form-control"
            placeholder="Ask about this codebase…"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            disabled={thinking}
          />
          <button className="btn btn-primary" type="submit" disabled={thinking || !input.trim()}>
            Ask
          </button>
        </div>
      </form>
    </aside>
  );
}

function MessageView({ message }: { message: AssistantMessage }) {
  if (message.role === "user") return <div className="msg-user">{message.text}</div>;
  return (
    <div className="msg-ai">
      {message.blocks?.map((b, i) => (
        <Block key={i} block={b} />
      ))}
      <div className="small text-muted mt-2">Generated by the mock provider</div>
    </div>
  );
}

function Block({ block }: { block: AnswerBlock }) {
  const { repo, openFile } = useExplorer();
  const [openIdx, setOpenIdx] = useState<number | null>(null);
  return (
    <div className="ai-block">
      <div className="mb-1">
        <EvidenceBadge kind={block.kind} />
      </div>
      <div>{block.text}</div>
      {block.refs?.map((ref, i) => {
        const code = openIdx === i ? excerpt(repo, ref) : undefined;
        return (
          <div key={formatRef(ref) + i}>
            <div className="d-flex gap-1">
              <button
                type="button"
                className="citation"
                onClick={() => openFile(ref.file, { start: ref.startLine, end: ref.endLine })}
                title="Open in source viewer"
              >
                {formatRef(ref)}
                {ref.symbol ? ` · ${ref.symbol}` : ""}
              </button>
              <button
                type="button"
                className="btn btn-sm btn-light border mt-1"
                aria-expanded={openIdx === i}
                aria-label="Toggle code excerpt"
                onClick={() => setOpenIdx(openIdx === i ? null : i)}
              >
                <i className="bi bi-code-slash" aria-hidden="true" />
              </button>
            </div>
            {code !== undefined && <pre className="excerpt">{code}</pre>}
          </div>
        );
      })}
    </div>
  );
}
